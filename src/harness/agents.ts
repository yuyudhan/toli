// omp subagent definitions for the lead's native `task` subagents, one per work kind: `.omp/agents/toli-<kind>.md`
// (gitignored; written by `bin/toli harness sync` and `bin/toli models set`). Each names its kind's model list from
// this machine's tables (src/harness/models.ts workModelList), so `agent: toli-qa` runs a testing slice on the model
// chosen for qa instead of the lead's own. omp tries the list in order and skips a model this machine cannot run;
// an empty list leaves the subagent on omp's own default.
import type { HarnessConfig } from "./harness.ts";
import { type ModelList, WORK_TYPES, type WorkType, workModelList } from "./models.ts";
import type { ShimItem } from "./sync.ts";

/** What each kind of work is, for the agent's description and prompt. */
const SUMMARY: Record<WorkType, string> = {
    scout: "read-only investigation: reads code, logs and records and writes the report its brief names",
    qa: "testing: runs test cases against a running product (browser, CLI, API) and records each result with evidence",
    desk: "QA desk: triages what testers find, checks for duplicates and files or updates bugs as its brief says",
    mechanical: "mechanical work: renames, bookkeeping, copying and data collection with no judgement calls",
    ship: "code changes: implements, tests and commits what its brief asks",
    verify: "independent verification of ship work: re-runs its checks and lands it when they hold",
    release: "release steps: cuts, tags and ships a project version",
};

/** The omp agent a lead names in its `task` tool for this kind of work. */
export function agentName(work: WorkType): string {
    return `toli-${work}`;
}

/** The agent file for one work kind: omp frontmatter (name, description, spawns, model list) and its prompt. */
export function agentDefinition(work: WorkType, models: ModelList): string {
    const shown = models.length === 0 ? "omp's default model" : models.join(", then ");
    const lines = [
        "---",
        "# Generated by `bin/toli harness sync` from config/machine.json; change the models with `bin/toli models set`.",
        `name: ${agentName(work)}`,
        `description: ${JSON.stringify(`toli jawan for ${work} work (briefs with "Work: ${work}"): ${SUMMARY[work]}. Model: ${shown}.`)}`,
        'spawns: "*"',
        ...(models.length === 0 ? [] : ["model:", ...models.map((model) => `    - ${JSON.stringify(model)}`)]),
        "---",
        "",
        `You are a toli jawan doing ${work} work: ${SUMMARY[work]}.`,
        "",
        "Your assignment is a toli brief (its first line is `TOLI_BRIEF v1`): follow it exactly. Work until its Stop when",
        "holds or you are blocked, run its Validate yourself and paste the output, and write what its Record line names.",
        "Never widen its scope, never weaken a test or check to make it pass, and never send signals to omp, claude, tmux,",
        "terminals or the lead. Your final message is your report: the outcome first, then the evidence.",
        "",
    ];
    return lines.join("\n");
}

/** Every agent file, relative to toli's root, from this machine's model tables. */
export function agentItems(config: HarnessConfig): ShimItem[] {
    return WORK_TYPES.map(
        (work): ShimItem => ({
            path: `.omp/agents/${agentName(work)}.md`,
            kind: "file",
            content: agentDefinition(work, workModelList("omp", work, config)),
            why: `omp subagent for ${work} work, on its configured models`,
        }),
    );
}
