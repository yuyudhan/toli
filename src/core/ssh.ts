import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { paths } from "./paths.ts";
import { type RunResult, run, runAsync, writeTextAtomic } from "./util.ts";

/** How long a shared connection stays up after its last call. */
const CONTROL_PERSIST = "10m";
/** A master answers `ssh -O check` locally at once; one that takes longer is wedged and would hang every call. */
const CHECK_TIMEOUT_MS = 2_000;
/** `ssh -G` only reads config files; it never connects. */
const RESOLVE_TIMEOUT_MS = 5_000;
// A unix socket path holds at most 103 bytes on macOS (104 with the NUL; Linux allows 107). %C expands to 40 hex
// characters, and a master first binds `<ControlPath>.<16 random characters>` before renaming it into place.
const SOCKET_PATH_MAX = 103;
const SOCKET_NAME_LENGTH = 40 + 17;
const SOCKET_NAME = /^[0-9a-f]{40}$/;

/** The client config toli's ssh calls read with `-F`, under the private state/ssh dir. */
export function sshConfigPath(): string {
    return join(paths.sshDir(), "config");
}

/** Quote an ssh_config argument; ssh splits unquoted arguments on whitespace. */
function configArg(value: string): string {
    return `"${value}"`;
}

/**
 * The generated client config: the user's and the system's ssh config first, then toli's connection sharing for
 * every host. ssh keeps the first value it reads for each option, so a host's own Control* settings win.
 */
function configText(dir: string): string {
    return [
        "# Generated by toli (src/core/ssh.ts); rewritten on every fleet ssh call.",
        "Include ~/.ssh/config",
        "Include /etc/ssh/ssh_config",
        "",
        "Host *",
        "    ControlMaster auto",
        `    ControlPath ${configArg(`${dir.replaceAll("%", "%%")}/%C`)}`,
        `    ControlPersist ${CONTROL_PERSIST}`,
        // The master carries every shared session, long `exec` runs included: it drops a link dead for two minutes
        // (not a short blip) so later calls connect afresh.
        "    ServerAliveInterval 30",
        "    ServerAliveCountMax 4",
        "",
    ].join("\n");
}

/**
 * Prepare state/ssh (mode 0700) and its client config; returns the config path, or null when this checkout's path
 * is too long for a control socket there (those calls then open their own connection, as before).
 */
function prepareSharing(): string | null {
    const dir = paths.sshDir();
    if (dir.length + 1 + SOCKET_NAME_LENGTH > SOCKET_PATH_MAX) return null;
    mkdirSync(dir, { recursive: true, mode: 0o700 });
    chmodSync(dir, 0o700);
    const config = sshConfigPath();
    const text = configText(dir);
    if (!existsSync(config) || readFileSync(config, "utf8") !== text) writeTextAtomic(config, text);
    return config;
}

/** The control socket in `ssh -G` output, or null when that call failed. */
function controlPath(resolved: RunResult): string | null {
    if (resolved.code !== 0) return null;
    const line = resolved.stdout.split("\n").find((entry) => entry.startsWith("controlpath "));
    return line ? line.slice("controlpath ".length).trim() : null;
}

/** Whether `socket` is a control socket toli made in state/ssh. */
function ownSocket(socket: string | null): socket is string {
    return socket?.startsWith(`${paths.sshDir()}/`) === true && existsSync(socket);
}

/**
 * Remove `host`'s control socket in state/ssh when no live master answers on it. ssh itself replaces a socket
 * nothing listens on, but a wedged master (stopped, or stuck) accepts the connection and never replies, which
 * would hang the call until its caller's timeout and every later call with it.
 */
function dropDeadMaster(config: string, host: string): void {
    if (!readdirSync(paths.sshDir()).some((name) => SOCKET_NAME.test(name))) return;
    const socket = controlPath(run(["ssh", "-F", config, "-G", host], { timeoutMs: RESOLVE_TIMEOUT_MS }));
    if (!ownSocket(socket)) return;
    const check = run(["ssh", "-F", config, "-O", "check", host], { timeoutMs: CHECK_TIMEOUT_MS });
    if (check.code !== 0) rmSync(socket, { force: true });
}

/** dropDeadMaster without blocking, so the checks for several hosts run at once. */
async function dropDeadMasterAsync(config: string, host: string): Promise<void> {
    if (!readdirSync(paths.sshDir()).some((name) => SOCKET_NAME.test(name))) return;
    const socket = controlPath(await runAsync(["ssh", "-F", config, "-G", host], { timeoutMs: RESOLVE_TIMEOUT_MS }));
    if (!ownSocket(socket)) return;
    const check = await runAsync(["ssh", "-F", config, "-O", "check", host], { timeoutMs: CHECK_TIMEOUT_MS });
    if (check.code !== 0) rmSync(socket, { force: true });
}

/**
 * ssh options that share one connection per host across toli's calls (OpenSSH ControlMaster), after dropping a
 * dead shared connection to `host`; empty when sharing is unavailable here.
 */
export function sshSharingArgs(host: string): string[] {
    const config = prepareSharing();
    if (!config) return [];
    dropDeadMaster(config, host);
    return ["-F", config];
}

/** sshSharingArgs without blocking (`ssh -G` can take seconds for a host behind a VPN that is down). */
export async function sshSharingArgsAsync(host: string): Promise<string[]> {
    const config = prepareSharing();
    if (!config) return [];
    await dropDeadMasterAsync(config, host);
    return ["-F", config];
}
