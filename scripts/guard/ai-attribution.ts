// No AI co-author trailers, Generated-by trailers, or "generated with <assistant name>" stamps in tracked files.
// Trailer-shaped lines are matched only at line start (optionally behind a comment or quote
// marker), so code that detects or strips such trailers, like src/commit.ts, is not flagged.
import { eachLine, type Guard, type Violation } from "../guard-lib.ts";

const AI = String.raw`(?:claude|anthropic|chatgpt|openai|gpt-?\d[\w.]*|copilot|gemini|codex|cursor|omp|oh my pi|ai|llm)`;
const CO_AUTHOR = new RegExp(String.raw`^\s*(?:[#/*>-]+\s*)?co-authored-by:.*\b${AI}\b`, "i");
const GENERATED_TRAILER = /^\s*(?:[#/*>-]+\s*)?generated-by:\s*\S/i;
const GENERATED_STAMP = new RegExp(String.raw`\bgenerated (?:by|with)\b.{0,40}?\b${AI}\b`, "i");

export default {
    name: "ai-attribution",
    run(files) {
        const violations: Violation[] = [];
        for (const { path, text } of files) {
            eachLine(text, (line, number) => {
                if (CO_AUTHOR.test(line)) violations.push({ path, line: number, message: "AI co-author trailer" });
                else if (GENERATED_TRAILER.test(line)) {
                    violations.push({ path, line: number, message: "Generated-by trailer" });
                } else if (GENERATED_STAMP.test(line)) {
                    violations.push({ path, line: number, message: "AI 'generated by' stamp" });
                }
            });
        }
        return violations;
    },
} satisfies Guard;
